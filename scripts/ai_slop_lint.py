from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

PLACEHOLDER_PATTERNS = (
    re.compile(
        r"\b(?:todo|fixme):?\s+(?:implement|fill|finish|wire|add)\b",
        re.IGNORECASE,
    ),
    re.compile(
        r"\b(?:placeholder|stub|dummy implementation|not implemented yet)\b",
        re.IGNORECASE,
    ),
)
CHATTY_COMMENT_PATTERN = re.compile(
    r"#.*\b(?:as an ai|generated by ai|chatgpt|codex generated)\b",
    re.IGNORECASE,
)


def _is_bare_pass(statement: ast.stmt) -> bool:
    if isinstance(statement, ast.Pass):
        return True
    if isinstance(statement, ast.Expr) and isinstance(
        statement.value,
        ast.Constant,
    ):
        return statement.value.value is Ellipsis
    return False


def _check_broad_exception_pass(path: Path, source: str) -> list[str]:
    try:
        tree = ast.parse(source, filename=str(path))
    except SyntaxError as error:
        return [
            f"{path}:{error.lineno}: could not parse Python file: {error.msg}"
        ]

    errors: list[str] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.ExceptHandler):
            continue
        if not isinstance(node.type, ast.Name) or node.type.id != "Exception":
            continue
        if node.body and all(_is_bare_pass(statement) for statement in node.body):
            errors.append(
                f"{path}:{node.lineno}: broad 'except Exception' must not silently pass"
            )
    return errors


def _check_text_patterns(path: Path, source: str) -> list[str]:
    errors: list[str] = []
    for line_number, line in enumerate(source.splitlines(), start=1):
        for pattern in PLACEHOLDER_PATTERNS:
            if pattern.search(line):
                errors.append(
                    f"{path}:{line_number}: placeholder implementation text "
                    "is not allowed"
                )
        if CHATTY_COMMENT_PATTERN.search(line):
            errors.append(
                f"{path}:{line_number}: chatty generated-code comment is not allowed"
            )
    return errors


def check_file(path: Path) -> list[str]:
    if path.name == "ai_slop_lint.py":
        return []
    source = path.read_text(encoding="utf-8")
    return [
        *_check_text_patterns(path, source),
        *_check_broad_exception_pass(path, source),
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Fail on common low-signal AI coding artifacts."
    )
    parser.add_argument("paths", nargs="*", type=Path)
    args = parser.parse_args(argv)

    paths = [
        path
        for path in args.paths
        if path.suffix == ".py" and path.exists()
    ]
    errors = [
        error
        for path in paths
        for error in check_file(path)
    ]
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
